// Fetch the game's icons from game-icons.net's GitHub repo and generate
// src/assets/icons.ts plus the icon list in src/assets/ATTRIBUTION.md.
// Run with `npm run icons` after changing ICON_SOURCES. Only SVG path data is
// kept (checked against a strict pattern), so nothing else from the download
// reaches the game.
import { readFileSync, writeFileSync } from 'node:fs';

/** Icon id → `author/name` in the game-icons repo. All are CC BY 3.0. */
const ICON_SOURCES: Record<string, string> = {
  // Base classes (advanced and tertiary classes use their base class's icon).
  warrior: 'lorc/visored-helm',
  rogue: 'lorc/cloak-dagger',
  mage: 'lorc/pointy-hat',
  cleric: 'lorc/holy-symbol',
  ranger: 'lorc/high-shot',
  monk: 'lorc/fist',
  bard: 'lorc/lyre',
  druid: 'lorc/oak',
  warlock: 'skoll/pentacle',
  engineer: 'lorc/gears',
  necromancer: 'sbed/death-skull',
  runeblade: 'lorc/rune-sword',
  'dark-knight': 'delapouite/black-knight-helm',
  // Summons.
  treant: 'cathelineau/tree-face',
  imp: 'lorc/imp',
  turret: 'sbed/turret',
  sentry: 'lorc/sentry-gun',
  wolf: 'lorc/wolf-head',
  'mirror-image': 'lorc/mirror-mirror',
  ancient: 'lorc/beech',
  fiend: 'lorc/daemon-skull',
  golem: 'delapouite/rock-golem',
  ghoul: 'delapouite/shambling-zombie',
  // Stats.
  hp: 'skoll/hearts',
  atk: 'lorc/broadsword',
  def: 'lorc/checked-shield',
  spd: 'lorc/wingfoot',
  // Shop offers.
  item: 'lorc/knapsack',
  signature: 'delapouite/round-star',
  training: 'delapouite/upgrade',
  // Settings.
  'sound-on': 'delapouite/sound-on',
  'sound-off': 'delapouite/speaker-off',
};

const AUTHORS: Record<string, string> = {
  lorc: 'Lorc',
  delapouite: 'Delapouite',
  skoll: 'Skoll',
  sbed: 'Sbed',
  cathelineau: 'Cathelineau',
};

const RAW = 'https://raw.githubusercontent.com/game-icons/icons/master';
const PATH_DATA = /^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/;
const BACKGROUND = 'M0 0h512v512H0z';

const titleCase = (slug: string) => slug.split('-').map((w) => w[0]!.toUpperCase() + w.slice(1)).join(' ');

async function fetchPath(source: string): Promise<string> {
  const res = await fetch(`${RAW}/${source}.svg`);
  if (!res.ok) throw new Error(`${source}: HTTP ${res.status}`);
  const svg = await res.text();
  const paths = [...svg.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]!).filter((d) => d !== BACKGROUND);
  if (paths.length === 0 || !paths.every((d) => PATH_DATA.test(d))) throw new Error(`${source}: unexpected SVG content`);
  return paths.join(' ');
}

const entries: string[] = [];
const credits: string[] = [];
for (const [id, source] of Object.entries(ICON_SOURCES)) {
  const [author, name] = source.split('/') as [string, string];
  const d = await fetchPath(source);
  const credit = { name: titleCase(name), author: AUTHORS[author] ?? titleCase(author), url: `https://game-icons.net/1x1/${source}.html` };
  entries.push(`  ${JSON.stringify(id)}: { d: ${JSON.stringify(d)}, ...credit(${JSON.stringify(credit.name)}, ${JSON.stringify(credit.author)}, ${JSON.stringify(credit.url)}) },`);
  credits.push(`- \`${id}\`: "${credit.name}" by ${credit.author}, ${credit.url}, CC BY 3.0`);
  console.log(`${id} ← ${source}`);
}

writeFileSync(
  'src/assets/icons.ts',
  `// Generated by src/sim/fetch-icons.ts (npm run icons). Do not edit by hand.
// Icons from game-icons.net, CC BY 3.0; see ATTRIBUTION.md and the in-game credits.

export interface IconDef {
  /** SVG path data on a 512×512 canvas. */
  d: string;
  name: string;
  author: string;
  url: string;
}

const credit = (name: string, author: string, url: string) => ({ name, author, url });

export const ICONS = {
${entries.join('\n')}
} satisfies Record<string, IconDef>;

export type IconId = keyof typeof ICONS;
`,
);

const attribution = readFileSync('src/assets/ATTRIBUTION.md', 'utf8');
const section = /(## Icons — game-icons\.net \(CC BY 3\.0\)\n\n)[\s\S]*?(\n## )/;
if (!section.test(attribution)) throw new Error('ATTRIBUTION.md: icon section not found');
writeFileSync('src/assets/ATTRIBUTION.md', attribution.replace(section, `$1${credits.join('\n')}\n$2`));
console.log(`Wrote ${entries.length} icons.`);
